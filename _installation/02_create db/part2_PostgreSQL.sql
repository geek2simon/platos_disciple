-- =====================================================================
-- Unified agent execution log
-- =====================================================================

CREATE TABLE AgentExecutionLog
(
    -- Identity
    ExecutionID                CHAR(36)          NOT NULL,
    ThreadID                   CHAR(36)          NULL,

    RequestStartedAt           TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL
                               DEFAULT CURRENT_TIMESTAMP(3),
    RequestCompletedAt         TIMESTAMP(3) WITHOUT TIME ZONE NULL,

    -- User request
    UserQuestion               TEXT              NOT NULL,
    UserCommand                VARCHAR(50)       NULL,
    Username                   VARCHAR(255)      NULL,
    CallingFrom                VARCHAR(255)      NULL,

    -- Router
    RouterIntent               VARCHAR(50)       NULL,
    RouterJSON                 JSONB             NULL,
    RouterSearchQuery          TEXT              NULL,
    RouterTopicTitle           VARCHAR(500)      NULL,
    ForceNewSearch             SMALLINT          NULL,

    -- Execution mode
    SearchMode                 VARCHAR(50)       NULL,
    PresentationMode           VARCHAR(50)       NULL,

    -- SQL execution
    GeneratedSQL               TEXT              NULL,
    SQLParameters              JSONB             NULL,
    RowsReturned               INT               NULL,

    SQLStartedAt               TIMESTAMP(3) WITHOUT TIME ZONE NULL,
    SQLCompletedAt             TIMESTAMP(3) WITHOUT TIME ZONE NULL,
    SQLElapsedMS               INT               NULL,
    SQLTraceJSON               JSONB             NULL,

    -- Search / retrieval
    SearchQuery                TEXT              NULL,
    NewSearch                  SMALLINT          NULL,

    MatchedChunks              INT               NULL,
    ChunkLimit                 INT               NULL,
    ChunksRetrieved            INT               NULL,
    UniqueDocumentsMatched     INT               NULL,
    DocumentsSent              INT               NULL,
    ChunksSentToGPT            INT               NULL,

    MaxChunksPerDoc            INT               NULL,
    MaxCharsPerChunk           INT               NULL,

    DocumentRankingMethod      VARCHAR(100)      NULL,
    RetrievalStatsJSON         JSONB             NULL,

    -- Original RAG log detail
    DocumentsUsed              JSONB             NULL,
    ChunksUsed                 JSONB             NULL,

    -- GPT / LLM usage
    -- SMALLINT preserves the existing Python 0/1 contract.
    GPTUsed                     SMALLINT          NOT NULL DEFAULT 0,
    GPTModel                    VARCHAR(150)      NULL,
    GPTPurpose                  VARCHAR(100)      NULL,

    PromptChars                 INT               NULL,
    PromptTokens                INT               NULL,
    CompletionTokens            INT               NULL,
    TotalTokens                 INT               NULL,

    GPTStartedAt                TIMESTAMP(3) WITHOUT TIME ZONE NULL,
    GPTCompletedAt              TIMESTAMP(3) WITHOUT TIME ZONE NULL,
    GPTElapsedMS                INT               NULL,

    GPTUsageJSON                JSONB             NULL,
    PromptSample                TEXT              NULL,

    -- Final answer
    FinalAnswer                 TEXT              NULL,
    AnswerChars                 INT               NULL,

    -- Status and timing
    ExecutionStatus             VARCHAR(30)       NOT NULL DEFAULT 'Success',
    ElapsedMS                   INT               NULL,

    -- Errors
    ErrorStage                  VARCHAR(50)       NULL,
    ErrorType                   VARCHAR(255)      NULL,
    ErrorMessage                TEXT              NULL,
    ErrorTraceback              TEXT              NULL,

    -- Audit
    CreatedAt                   TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL
                               DEFAULT CURRENT_TIMESTAMP(3),
    UpdatedAt                   TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL
                               DEFAULT CURRENT_TIMESTAMP(3),

    -- Constraints
    CONSTRAINT PK_AgentExecutionLog
        PRIMARY KEY (ExecutionID),

    CONSTRAINT CK_AgentExecutionLog_Status
        CHECK
        (
            ExecutionStatus IN
            (
                'Success', 'Failed', 'NoResults', 'Partial', 'Cancelled',
                'Ambiguous', 'EmptyForcedRouteQuery', 'NoDocumentBound'
            )
        ),

    CONSTRAINT CK_AgentExecutionLog_GPTUsed
        CHECK (GPTUsed IN (0, 1)),

    CONSTRAINT CK_AgentExecutionLog_NewSearch
        CHECK (NewSearch IS NULL OR NewSearch IN (0, 1)),

    CONSTRAINT CK_AgentExecutionLog_ForceNewSearch
        CHECK (ForceNewSearch IS NULL OR ForceNewSearch IN (0, 1))
);

-- UpdatedAt is maintained by the shared set_updated_at() function.
CREATE TRIGGER TR_AgentExecutionLog_SetUpdatedAt
BEFORE UPDATE ON AgentExecutionLog
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

