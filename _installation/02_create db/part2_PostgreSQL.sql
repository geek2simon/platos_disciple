CREATE OR REPLACE VIEW vw_DocumentStatus AS
SELECT
    Extension,
    ParseStatus,
    COUNT(*) AS FileCount,
    ROUND(SUM(FileSizeBytes)::NUMERIC / 1024 / 1024, 2) AS TotalSizeMB
FROM Document
GROUP BY Extension, ParseStatus;

CREATE OR REPLACE VIEW vw_DocumentWithSummary AS
SELECT
    d.DocID,
    d.FullPath,
    d.RelativePath,
    d.FolderLevel1,
    d.FolderLevel2,
    d.FolderLevel3,
    d.FileName,
    d.Extension,
    d.FileSizeBytes,
    d.ModifiedTime,
    d.ParseStatus,
    s.Title,
    s.DocType,
    s.Summary,
