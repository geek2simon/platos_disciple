-- =====================================================
-- Shared trigger function for UpdatedAt columns
-- =====================================================
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.UpdatedAt := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

-- =====================================================
-- 1. Document: one row per physical file
-- =====================================================
CREATE TABLE Document
(
    DocID              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    FullPath           VARCHAR(1200) NOT NULL,
    RelativePath       VARCHAR(1000),
    FolderPath         VARCHAR(1000),

    FolderLevel1       VARCHAR(255),
    FolderLevel2       VARCHAR(255),
    FolderLevel3       VARCHAR(255),
    FolderLevel4       VARCHAR(255),

    FileName           VARCHAR(500) NOT NULL,
    Extension          VARCHAR(30),

    FileSizeBytes      BIGINT,
    ModifiedTime       TIMESTAMP WITHOUT TIME ZONE,

    FileHashSHA256     CHAR(64),
    Metadata            JSONB,

    ParseStatus        VARCHAR(30) DEFAULT 'Pending',
    ParseTime          TIMESTAMP WITHOUT TIME ZONE,
    ErrorMessage       TEXT,

    CreatedAt          TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt          TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT UX_Document_FullPath UNIQUE (FullPath)
);

CREATE INDEX IX_Document_FileName      ON Document (FileName);
CREATE INDEX IX_Document_Extension     ON Document (Extension);
CREATE INDEX IX_Document_ParseStatus   ON Document (ParseStatus);
CREATE INDEX IX_Document_Folder1       ON Document (FolderLevel1);
CREATE INDEX IX_Document_Folder2       ON Document (FolderLevel2);
CREATE INDEX IX_Document_ModifiedTime  ON Document (ModifiedTime);
CREATE INDEX IX_Document_FileHash      ON Document (FileHashSHA256);

CREATE TRIGGER TR_Document_SetUpdatedAt
BEFORE UPDATE ON Document
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

-- =====================================================
-- 2. DocumentText: full extracted text per document
-- =====================================================
CREATE TABLE DocumentText
(
    DocID              BIGINT PRIMARY KEY,

    RawText            TEXT,
    CharacterCount     INT,
    WordCount          INT,

    ExtractedAt        TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_DocumentText_Document
        FOREIGN KEY (DocID)
        REFERENCES Document(DocID)
        ON DELETE CASCADE
);

-- =====================================================
-- 3. DocumentPageText: PDF/page-level text
-- =====================================================
CREATE TABLE DocumentPageText
(
    PageTextID         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    DocID              BIGINT NOT NULL,
    PageNo             INT NOT NULL,

    PageText           TEXT,
    CharacterCount     INT,

    CreatedAt          TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_DocumentPageText_Document
        FOREIGN KEY (DocID)
        REFERENCES Document(DocID)
        ON DELETE CASCADE,

    CONSTRAINT UX_DocumentPageText UNIQUE (DocID, PageNo)
);

CREATE INDEX IX_DocumentPageText_DocID ON DocumentPageText (DocID);

-- =====================================================
-- 4. DocumentSheetText: Excel sheet-level text
-- =====================================================
CREATE TABLE DocumentSheetText
(
    SheetTextID        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    DocID              BIGINT NOT NULL,
    SheetName          VARCHAR(255) NOT NULL,

    UsedRange          VARCHAR(100),
    RowCount           INT,
    ColumnCount        INT,

    SheetText          TEXT,
    CharacterCount     INT,

    CreatedAt          TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_DocumentSheetText_Document
        FOREIGN KEY (DocID)
        REFERENCES Document(DocID)
        ON DELETE CASCADE,

    CONSTRAINT UX_DocumentSheetText UNIQUE (DocID, SheetName)
);

CREATE INDEX IX_DocumentSheetText_DocID     ON DocumentSheetText (DocID);
CREATE INDEX IX_DocumentSheetText_SheetName ON DocumentSheetText (SheetName);

-- =====================================================
-- 5. DocumentChunk: chunks for retrieval / embedding
-- =====================================================
CREATE TABLE DocumentChunk
(
    ChunkID            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    DocID              BIGINT NOT NULL,

    ChunkNo            INT NOT NULL,
    ChunkSource        VARCHAR(50),       -- FullText / Page / Sheet / Manual

    PageNo             INT NULL,
    SheetName          VARCHAR(255) NULL,

    ChunkText          TEXT,

    StartPos           INT,
    EndPos             INT,

    CharacterCount     INT,
    TokenEstimate      INT,

    CreatedAt          TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_DocumentChunk_Document
        FOREIGN KEY (DocID)
        REFERENCES Document(DocID)
        ON DELETE CASCADE,

    CONSTRAINT UX_DocumentChunk UNIQUE (DocID, ChunkNo)
);

CREATE INDEX IX_DocumentChunk_DocID     ON DocumentChunk (DocID);
CREATE INDEX IX_DocumentChunk_Source    ON DocumentChunk (ChunkSource);
CREATE INDEX IX_DocumentChunk_PageNo    ON DocumentChunk (PageNo);
CREATE INDEX IX_DocumentChunk_SheetName ON DocumentChunk (SheetName);

-- =====================================================
-- 6. DocumentSummary: GPT document-level understanding
-- =====================================================
CREATE TABLE DocumentSummary
(
    DocID              BIGINT PRIMARY KEY,

    Title              VARCHAR(500),

    DocType            VARCHAR(100),
    Summary            TEXT,

    Keywords           TEXT,
    Topics             TEXT,
    Companies          TEXT,
    People             TEXT,
