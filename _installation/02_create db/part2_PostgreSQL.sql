-- =========================================================
-- View 2: Daily usage summary
-- =========================================================
CREATE OR REPLACE VIEW vw_AgentExecutionLog_DailyStats AS
SELECT
    RequestStartedAt::DATE AS ExecutionDate,
    COUNT(*) AS RequestCount,
    SUM(CASE WHEN ExecutionStatus = 'Success'   THEN 1 ELSE 0 END) AS SuccessCount,
    SUM(CASE WHEN ExecutionStatus = 'Failed'    THEN 1 ELSE 0 END) AS FailedCount,
    SUM(CASE WHEN ExecutionStatus = 'NoResults' THEN 1 ELSE 0 END) AS NoResultsCount,
    SUM(CASE WHEN GPTUsed = 1                   THEN 1 ELSE 0 END) AS GPTRequestCount,
    SUM(COALESCE(PromptTokens, 0)) AS PromptTokens,
    SUM(COALESCE(CompletionTokens, 0)) AS CompletionTokens,
    SUM(COALESCE(TotalTokens, 0)) AS TotalTokens,
    ROUND(AVG(ElapsedMS), 0) AS AverageElapsedMS,
    MAX(ElapsedMS) AS MaximumElapsedMS,
    ROUND(AVG(SQLElapsedMS), 0) AS AverageSQLElapsedMS,
    ROUND(AVG(GPTElapsedMS), 0) AS AverageGPTElapsedMS
FROM AgentExecutionLog
GROUP BY RequestStartedAt::DATE;

-- =========================================================
-- View 3: Intent and search mode performance
-- =========================================================
CREATE OR REPLACE VIEW vw_AgentExecutionLog_IntentStats AS
SELECT
    COALESCE(RouterIntent, '(No Intent)') AS RouterIntent,
    COALESCE(SearchMode, '(No Search Mode)') AS SearchMode,
    COUNT(*) AS RequestCount,
    SUM(CASE WHEN ExecutionStatus = 'Success'   THEN 1 ELSE 0 END) AS SuccessCount,
    SUM(CASE WHEN ExecutionStatus = 'Failed'    THEN 1 ELSE 0 END) AS FailedCount,
    SUM(CASE WHEN ExecutionStatus = 'NoResults' THEN 1 ELSE 0 END) AS NoResultsCount,
    ROUND(AVG(RowsReturned), 1) AS AverageRowsReturned,
    ROUND(AVG(ElapsedMS), 0) AS AverageElapsedMS,
    ROUND(AVG(TotalTokens), 0) AS AverageTokens
FROM AgentExecutionLog
GROUP BY
    COALESCE(RouterIntent, '(No Intent)'),
    COALESCE(SearchMode, '(No Search Mode)');

-- =========================================================
-- View 4: Error report
-- =========================================================
CREATE OR REPLACE VIEW vw_AgentExecutionLog_Errors AS
SELECT
    ExecutionID,
    ThreadID,
    RequestStartedAt,
    UserQuestion,
    RouterIntent,
    SearchMode,
    ErrorStage,
    ErrorType,
    ErrorMessage,
    ErrorTraceback,
    ElapsedMS
FROM AgentExecutionLog
WHERE ExecutionStatus = 'Failed'
ORDER BY RequestStartedAt DESC;

-- =========================================================
-- View 5: RAG usage and document retrieval summary
-- =========================================================
CREATE OR REPLACE VIEW vw_AgentExecutionLog_RAGStats AS
SELECT
    ExecutionID,
    ThreadID,
    RequestStartedAt,
    UserQuestion,
    RouterIntent,
    SearchQuery,
    MatchedChunks,
    ChunkLimit,
    ChunksRetrieved,
    UniqueDocumentsMatched,
    DocumentsSent,
    ChunksSentToGPT,
    DocumentRankingMethod,
    PromptTokens,
    CompletionTokens,
    TotalTokens,
    ElapsedMS,
    ExecutionStatus
FROM AgentExecutionLog
WHERE SearchMode = 'RAG_FULLTEXT'
ORDER BY RequestStartedAt DESC;

